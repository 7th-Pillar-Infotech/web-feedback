#!/usr/bin/env node
/**
 * Bakes the browser assets into the Worker.
 *
 * A Worker can't read files from disk at runtime, so the widget (and the snapdom
 * capture engine) are embedded as JS string constants. Run before every deploy —
 * `npm run deploy` does it for you via `predeploy`.
 *
 * JSON.stringify is used rather than a template literal because the sources
 * contain backticks and ${…}, which would break interpolation.
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const skill = join(here, '..');

const widget = readFileSync(join(skill, 'widget', 'feedback-widget.js'), 'utf8');

// snapdom comes from the Node collector's node_modules. If it hasn't been
// installed, the Worker simply won't serve /vendor/snapdom.js and the widget
// falls back to the CDN — so this is a warning, not an error.
const snapdomPath = join(skill, 'server', 'node_modules', '@zumer', 'snapdom', 'dist', 'snapdom.js');
let snapdom = '';
if (existsSync(snapdomPath)) {
  snapdom = readFileSync(snapdomPath, 'utf8');
} else {
  console.warn(
    '[build] snapdom not found at %s — the Worker will not serve /vendor/snapdom.js\n' +
      '        (the widget falls back to the CDN). Run `npm install` in ../server to bundle it.',
    snapdomPath
  );
}

mkdirSync(join(here, 'src'), { recursive: true });
writeFileSync(
  join(here, 'src', 'assets.gen.js'),
  '// GENERATED by build.mjs — do not edit.\n' +
    `export const WIDGET_JS = ${JSON.stringify(widget)};\n` +
    `export const SNAPDOM_JS = ${JSON.stringify(snapdom)};\n`
);

console.log(
  '[build] wrote src/assets.gen.js (widget %dkB, snapdom %dkB)',
  Math.round(widget.length / 1024),
  Math.round(snapdom.length / 1024)
);
